import { expect, it, vi } from "vitest";
import { cancelQueueTask, openQueueTask } from "./queueActions";
const youtube = { jobId: "10", platform: "youtube" as const, title: "A", state: "downloading" as const, percent: null, errorCode: null, displayName: null };
it("routes cancel and completed-location actions to the exact platform and job", async () => {
  const api = { cancelYoutube: vi.fn(), cancelInstagram: vi.fn(), cancelX:vi.fn(), openYoutube: vi.fn(), openInstagram: vi.fn(), openX:vi.fn(),cancelBilibili:vi.fn(),openBilibili:vi.fn() };
  await cancelQueueTask(youtube, api);
  await cancelQueueTask({ ...youtube, jobId: "11", platform: "instagram" }, api);
  await cancelQueueTask({ ...youtube, jobId: "12", platform: "x" }, api);
  await openQueueTask({ ...youtube, state: "completed", displayName: "A.mp4" }, api);
  await openQueueTask({ ...youtube, jobId: "11", platform: "instagram", state: "partial", displayName: "Post" }, api);
  await openQueueTask({ ...youtube, jobId: "12", platform: "x", state: "partial", displayName: "X post" }, api);
  expect(api.cancelYoutube).toHaveBeenCalledExactlyOnceWith("10");
  expect(api.cancelInstagram).toHaveBeenCalledExactlyOnceWith("11");
  expect(api.openYoutube).toHaveBeenCalledExactlyOnceWith("10");
  expect(api.openInstagram).toHaveBeenCalledExactlyOnceWith("11");
  expect(api.cancelX).toHaveBeenCalledExactlyOnceWith("12");
  expect(api.openX).toHaveBeenCalledExactlyOnceWith("12");
  await cancelQueueTask({...youtube,jobId:"13",platform:"bilibili"},api);
  await openQueueTask({...youtube,jobId:"13",platform:"bilibili",state:"completed",displayName:"Bili.mp4"},api);
  expect(api.cancelBilibili).toHaveBeenCalledExactlyOnceWith("13");
  expect(api.openBilibili).toHaveBeenCalledExactlyOnceWith("13");
});
